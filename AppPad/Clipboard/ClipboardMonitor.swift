import AppKit
import UniformTypeIdentifiers

// Polls NSPasteboard.changeCount (there is no change notification) and stores new content.
final class ClipboardMonitor: NSObject {
    private let store: ClipboardStore
    private let pasteboard = NSPasteboard.general
    private let queue = DispatchQueue(label: "AppPad.clipboard.ingest", qos: .utility)
    private var timer: Timer?
    private var lastChangeCount: Int
    private var ignoredChangeCount: Int?
    private var knownSources: Set<String>

    private static let interval: TimeInterval = 0.4
    private static let maxTextBytes = 4_000_000
    private static let maxRTFBytes = 1_000_000
    // nspasteboard.org markers: passwords, transient and generated content.
    private static let skippedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
    ]

    init(store: ClipboardStore) {
        self.store = store
        lastChangeCount = NSPasteboard.general.changeCount
        knownSources = Set(store.sourceApps().map(\.bundleID))
        super.init()
    }

    func start() {
        guard timer == nil else { return }
        lastChangeCount = pasteboard.changeCount   // ignore what was copied while stopped
        let timer = Timer(timeInterval: Self.interval, target: self, selector: #selector(tick), userInfo: nil, repeats: true)
        timer.tolerance = 0.1
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    // Our own writes (paste from history) must not create new entries.
    func ignore(changeCount: Int) {
        ignoredChangeCount = changeCount
        lastChangeCount = changeCount
    }

    @objc private func tick() {
        let count = pasteboard.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count
        guard count != ignoredChangeCount else { return }
        let captures = makeCaptures()
        guard !captures.isEmpty else { return }

        let prefs = Preferences.shared
        let options = ClipIngestOptions(
            imageQuality: Double(prefs.clipboardImageQuality) / 100,
            historyLimit: prefs.clipboardHistoryLimit,
            retentionDays: prefs.clipboardRetentionDays
        )
        let store = store
        queue.async {
            for capture in captures.reversed() {      // first file ends up on top
                do {
                    try store.ingest(capture, options: options)
                } catch {
                    NSLog("Clipboard ingest failed: \(error)")
                }
            }
            DispatchQueue.main.async {
                NotificationCenter.default.post(name: .clipboardStoreDidChange, object: nil)
            }
        }
    }

    // Image files (Finder, chat apps' temp files) become image items with their own stored copy,
    // one per file; other files stay a single file-reference item.
    private func makeCaptures() -> [ClipCapture] {
        let types = Set((pasteboard.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.skippedTypes) else { return [] }

        // Copies made inside our own panels have no meaningful source app.
        let ownWindow = NSApp.keyWindow is LaunchpadPanel
        let front = ownWindow ? nil : NSWorkspace.shared.frontmostApplication
        let bundleID = front?.bundleIdentifier
        if let bundleID, Preferences.shared.clipboardIgnoredApps.contains(bundleID) { return [] }

        var capture = ClipCapture(kind: .text, sourceBundleID: bundleID, sourceName: front?.localizedName)
        let fileURLs = pasteboard.readObjects(
            forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]
        ) as? [URL] ?? []

        if let front, let bundleID, !knownSources.contains(bundleID) {
            capture.sourceIcon = Self.iconPNG(for: front)
            knownSources.insert(bundleID)
        }

        if !fileURLs.isEmpty {
            if fileURLs.allSatisfy(Self.isImageFile) {
                return fileURLs.map { url in
                    var item = capture
                    item.kind = .image
                    item.imageFile = url
                    item.sourcePath = url.path
                    item.text = url.lastPathComponent      // searchable by file name
                    return item
                }
            }
            capture.kind = .file
            capture.text = fileURLs.map(\.path).joined(separator: "\n")
        } else if let string = pasteboard.string(forType: .string),
                  !string.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            guard string.utf8.count <= Self.maxTextBytes else { return [] }
            capture.kind = .text
            capture.text = string
            if let rtf = pasteboard.data(forType: .rtf), rtf.count <= Self.maxRTFBytes {
                capture.rtf = rtf
            }
        } else if let image = pasteboard.data(forType: .png) ?? pasteboard.data(forType: .tiff) {
            guard image.count <= ClipboardStore.maxImageBytes else { return [] }
            capture.kind = .image
            capture.imageData = image
        } else {
            return []
        }
        return [capture]
    }

    private static func isImageFile(_ url: URL) -> Bool {
        let type = (try? url.resourceValues(forKeys: [.contentTypeKey]))?.contentType
        return type?.conforms(to: .image) == true
    }

    // Own 64 px copy of the app icon.
    private static func iconPNG(for app: NSRunningApplication) -> Data? {
        guard let icon = app.icon ?? app.bundleURL.map({ NSWorkspace.shared.icon(forFile: $0.path) }) else { return nil }
        let side = 64
        guard let rep = NSBitmapImageRep(
            bitmapDataPlanes: nil, pixelsWide: side, pixelsHigh: side, bitsPerSample: 8,
            samplesPerPixel: 4, hasAlpha: true, isPlanar: false, colorSpaceName: .deviceRGB,
            bytesPerRow: 0, bitsPerPixel: 0
        ) else { return nil }
        rep.size = NSSize(width: side, height: side)
        NSGraphicsContext.saveGraphicsState()
        NSGraphicsContext.current = NSGraphicsContext(bitmapImageRep: rep)
        icon.draw(in: NSRect(x: 0, y: 0, width: side, height: side))
        NSGraphicsContext.restoreGraphicsState()
        return rep.representation(using: .png, properties: [:])
    }
}
